const axePath = process.env.TEBU_AXE_PATH
async function audit(page, name) {
  if (!axePath) return
  await page.waitForTimeout(450)
  await page.addScriptTag({ path: axePath })
  const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } })).violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })))
  reports.push({ name, violations })

}
async function noOverflow(page, name) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow: ${name}`)
  const bad = await page.locator('.app-content').evaluate(element => element.scrollWidth > element.clientWidth + 1)
  assert.equal(bad, false, `App content overflow: ${name}`)
}
