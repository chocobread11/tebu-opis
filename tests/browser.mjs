const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
const page = await context.newPage()
page.setDefaultTimeout(15000)
const reports = []
async function audit(name) {
  if (!process.env.TEBU_AXE_PATH) return
  await page.waitForTimeout(450)
  await page.addScriptTag({ path: process.env.TEBU_AXE_PATH })
  const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } })).violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })))
  reports.push({ name, violations })
}
