import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.setDefaultTimeout(10000)
try {
  await page.goto(process.env.TEBU_TEST_URL || 'http://127.0.0.1:3042')
  const quantity = page.getByRole('spinbutton', { name: 'The Everyday Flask quantity', exact: true })
  await quantity.waitFor()
  assert.equal(await quantity.inputValue(), '0')
  assert.equal(await page.getByRole('button', { name: 'Remove one The Everyday Flask', exact: true }).isDisabled(), true)
  await quantity.click()
  await quantity.press('ArrowUp')
  assert.equal(await quantity.inputValue(), '1')
  const quantityMax = await quantity.getAttribute('aria-valuemax')
  await quantity.press('End')
  assert.equal(await quantity.inputValue(), quantityMax)
  assert.equal(await page.getByRole('button', { name: 'Add one The Everyday Flask', exact: true }).isDisabled(), true)
  await quantity.press('Home')
  assert.equal(await quantity.inputValue(), '0')
  await quantity.fill('3')
  await quantity.press('Tab')
  await page.getByRole('listitem').filter({ hasText: 'The Everyday Flask' }).waitFor()

  await page.goto(new URL('/admin/calendar', page.url()).href)
  await page.locator('.calendar-date.available').first().click()
  const capacity = page.locator('#day-capacity')
  await capacity.waitFor()
  const initialCapacity = Number(await capacity.inputValue())
  await capacity.focus()
  await capacity.press('ArrowUp')
  assert.equal(await capacity.inputValue(), String(initialCapacity + 1))
  const status = page.getByRole('combobox', { name: 'Day status', exact: true })
  assert.equal(await status.evaluate(element => element.tagName), 'SELECT')
  await status.selectOption('AL')
  assert.equal(await status.inputValue(), 'AL')

  await page.getByRole('link', { name: 'Log', exact: true }).click()
  await page.getByRole('button', { name: 'Log harvest', exact: true }).click()
  const variety = page.getByRole('combobox', { name: 'Tebu variety', exact: true })
  await variety.selectOption('tebu-2')
  assert.equal(await variety.inputValue(), 'tebu-2')
  assert.equal(await variety.locator('option').count(), 2)
  const bottles = page.getByRole('spinbutton', { name: 'Ready 500 ml bottles', exact: true })
  await bottles.focus()
  await bottles.press('ArrowDown')
  assert.equal(await bottles.inputValue(), '0')
  await bottles.press('End')
  assert.equal(await bottles.inputValue(), '10000')
  assert.equal(await page.getByRole('button', { name: 'Increase ready 500 ml bottles', exact: true }).isDisabled(), true)
  await bottles.fill('7')
  await bottles.press('Tab')
  const weight = page.getByRole('spinbutton', { name: 'Cane harvested (kg) optional', exact: true })
  await weight.fill('12.50')
  await weight.press('Tab')
  await page.getByRole('button', { name: 'Increase cane weight', exact: true }).click()
  assert.equal(await weight.inputValue(), '12.51')
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await page.getByRole('dialog').evaluate(element => element.scrollWidth > element.clientWidth + 1), false)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await mkdir('test-results', { recursive: true })
  await page.screenshot({ path: 'test-results/shadcn-harvest-fields.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add expense', exact: true }).click()
  const amount = page.getByRole('spinbutton', { name: 'Amount (RM)', exact: true })
  assert.equal(await amount.evaluate(element => element.required), true)
  await amount.fill('12.50')
  await amount.press('Tab')
  await page.getByRole('button', { name: 'Increase expense amount', exact: true }).click()
  assert.equal(await amount.inputValue(), '12.51')
  await page.getByRole('dialog').getByRole('button', { name: 'Add expense', exact: true }).click()
  await page.getByRole('cell', { name: 'RM 12.51', exact: true }).first().waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: native select labels/options; number field typing, keyboard controls, min/max, disabled steppers, decimal increments and required inputs; responsive dialogs; expense persistence.')
} catch (error) {
  await mkdir('test-results', { recursive: true })
  await page.screenshot({ path: 'test-results/fields-failure.png', fullPage: true })
  throw error
} finally { await browser.close() }
